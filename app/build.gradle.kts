// Release signing is read from keystore.properties (kept out of the source tree).
val keystore = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.isFile) file.inputStream().use { load(it) }
}

android {
    namespace = "io.github.gap19.flacker"
    compileSdk = 37

    defaultConfig {
        applicationId = "io.github.gap19.flacker"
        // FLAC is decoded by the platform MediaCodec, available from Android 8.1 (API 27).
        minSdk = 27
        targetSdk = 36
        versionCode = 3
        versionName = "1.0.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (keystore.containsKey("storeFile")) {
            create("release") {
                storeFile = rootProject.file(keystore.getProperty("storeFile"))
                storePassword = keystore.getProperty("storePassword")
                keyAlias = keystore.getProperty("keyAlias")
                keyPassword = keystore.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    // The app is English only; keep library strings (Compose, Material, Media3) in English too.
    androidResources {
        localeFilters += listOf("en")
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }
}

